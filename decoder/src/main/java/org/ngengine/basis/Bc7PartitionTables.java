    private Bc7PartitionTables() {
    }

    static int partition2(int partition, int pixel) {
        return PARTITION2.charAt(partition * 16 + pixel) - '0';
    }

    static int partition3(int partition, int pixel) {
        return PARTITION3.charAt(partition * 16 + pixel) - '0';
    }

    static int[] partition2Map(int partition) {
        int[] map = new int[16];
        for (int i = 0; i < map.length; i++) {
            map[i] = partition2(partition, i);
        }
        return map;
    }

    static int[] partition3Map(int partition) {
        int[] map = new int[16];
        for (int i = 0; i < map.length; i++) {
            map[i] = partition3(partition, i);
        }
        return map;
    }

    static int partition2Mask(int partition) {
        int mask = 0;
        for (int i = 0; i < 16; i++) {
            mask |= partition2(partition, i) << i;
        }
        return mask;
    }

    static int partition3Masks(int partition) {
        int mask = 0;
        for (int i = 0; i < 16; i++) {
            int subset = partition3(partition, i);
            if (subset == 1) {
                mask |= 1 << i;
            } else if (subset == 2) {
                mask |= 0x10000 << i;
            }
        }
        return mask;
    }
