    static int seedForUniquePattern(
            int blockWidth,
            int blockHeight,
            int numberOfPartitions,
            int uniquePatternIndex) {
        int blockSizeIndex = XuastcLdrImageHeader.findAstcBlockSizeIndex(blockWidth, blockHeight);
        if (numberOfPartitions == 2) {
            return seedFrom(PARTITION_2[blockSizeIndex], uniquePatternIndex);
        }
        if (numberOfPartitions == 3) {
            return seedFrom(PARTITION_3[blockSizeIndex], uniquePatternIndex);
        }
        throw new BasisDecodeException("Unsupported ASTC partition count: " + numberOfPartitions);
    }

    private static int seedFrom(int[] table, int uniquePatternIndex) {
        if (uniquePatternIndex < 0 || uniquePatternIndex >= table.length) {
            throw new BasisDecodeException("Invalid XUASTC partition pattern index");
        }
        return table[uniquePatternIndex];
    }

